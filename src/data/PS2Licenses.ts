function makeLicense([_square, fullName, cost, ...items]: typeof PS2LicenseData[number], sortOrder: number): License {
	const family = fullName.replace(/ \d+$/, "");
	let group: string;
	let what: number | string[] = items;
	let text = items.join("\n");
	if (esperImages[fullName]) {
		group = "Esper";
		what = [fullName];
		text = `Summon ${fullName}.`;
	} else if (fullName.startsWith("Quickening ")) {
		group = "Quickening";
		what = 1;
		text = "Learn a Quickening. Only one character can claim this square; each character can learn three.";
	} else if (fullName.startsWith("+")) {
		group = "HP";
		what = parseInt(fullName.slice(1), 10);
		text = `Increase max HP by ${what}.`;
	} else if (["Battle Lore", "Magick Lore", "Gambit Slot"].includes(family)) {
		group = family;
		what = 1;
		text = family === "Gambit Slot" ? "Add an additional gambit slot." : `Increase ${family === "Battle Lore" ? "Strength" : "Magick Power"} by 1.`;
	} else if (/Lore|Swiftness|Channeling|Shield Block/.test(family) || !items.length) {
		group = "Passive";
		what = [fullName];
		text = effects[fullName] ?? ({
			"Shield Block": "Increase chance to block with a shield by 5%.",
			Swiftness: "Reduce action time by 10%.",
			Channeling: "Reduce magick MP cost by 10%.",
			"Potion Lore": "Potions restore more HP.",
			"Ether Lore": "Ethers restore more MP.",
			"Phoenix Lore": "Phoenix Downs restore more HP.",
			"Remedy Lore": "Remedies remove additional status ailments.",
		} as Record<string, string>)[family];
		const rank = Number(fullName.split(" ").at(-1));
		if (family === "Potion Lore" || family === "Ether Lore") {
			text = `${family === "Potion Lore" ? "Potions restore" : "Ethers restore"} ${[10, 15, 25][rank - 1]}% more ${family === "Potion Lore" ? "HP" : "MP"}.`;
		} else if (family === "Phoenix Lore") {
			text = "Phoenix Downs restore an additional 10% of the revived ally's max HP.";
		} else if (family === "Remedy Lore") {
			text = `Remedies additionally remove ${["Sleep, Sap, Immobilize, and Disable", "Petrify, Confuse, and Oil", "Stop, Doom, and Disease"][rank - 1]}.`;
		}
	} else if (effects[fullName]) {
		group = "Technicks";
		text = effects[fullName];
	} else {
		group = ({
			Ribbon: "Accessories", "Shell Shield": "Shields", "Ensanguined Shield": "Shields", "Zodiac Escutcheon": "Shields",
			"Blood Sword": "Swords", Sagittarius: "Bows", "Dragon Whisker": "Spears", "Zodiac Spear": "Spears",
			Masamune: "Katana", Excalibur: "Greatswords", Tournesol: "Greatswords", "Rod of Faith": "Rods",
			"Staff of the Magi": "Staves", Danjuro: "Daggers", "Whale Whisker": "Poles", "Yagyu Darkblade": "Ninja Swords",
		} as Record<string, string>)[fullName] ?? family;
	}
	return {
		fullName, cost, text, sortOrder,
		limited: group === "Esper" || group === "Quickening",
		grants: { group, what },
		image: esperImages[fullName] ?? (group === "Quickening" ? Star : undefined),
	};
}

export const PS2Licenses = PS2LicenseData.map(makeLicense);
const byName = new Map(PS2Licenses.map(l => [l.fullName, l]));
export function PS2LicenseByName(name: string): License {
	const license = byName.get(name);
	if (!license) throw new Error(`Unknown PS2 license ${name}`);
	return license;
}

const groups = new Map<string, LicenseGroup>();
for (const license of PS2Licenses) {
	const name = license.grants!.group;
	if (!groups.has(name)) groups.set(name, { name, contents: [] });
	groups.get(name)!.contents.push(license);
}
export const PS2LicenseGroups = [...groups.values()];
export const PS2Espers = groups.get("Esper")!.contents;
export const PS2Quickenings = groups.get("Quickening")!.contents;
export const PS2LimitedLicenses = [...PS2Espers, ...PS2Quickenings];
